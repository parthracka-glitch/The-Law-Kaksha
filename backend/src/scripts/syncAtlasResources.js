async function sync() {
  console.log(`Synchronizing ${REAL_RESOURCES.length} real study resources...`);

  // 1. Update local database
  const resourcesTable = Database.table("resources");
  const existing = resourcesTable.find();
  for (const ex of existing) {
    resourcesTable.delete(ex.id);
  }
  for (const r of REAL_RESOURCES) {
    resourcesTable.insert(r);
  }
  console.log(`Local DB updated with ${resourcesTable.count()} real resources.`);

  // 2. Connect to MongoDB Atlas
  await mongoose.connect(process.env.MONGODB_URI);
  console.log("Connected to MongoDB Atlas.");

  const realIds = REAL_RESOURCES.map((r) => r.id);
  const delRes = await Resource.deleteMany({ id: { $nin: realIds } });
  console.log(`Deleted ${delRes.deletedCount} non-matching resources from Atlas.`);

  for (const item of REAL_RESOURCES) {
    await Resource.findOneAndUpdate({ id: item.id }, { $set: item }, { upsert: true, returnDocument: "after" });
  }

  const finalCount = await Resource.countDocuments();
  console.log(`Atlas Resource collection now has ${finalCount} synced resources.`);
  process.exit(0);
}

sync().catch((err) => {
  console.error("Sync error:", err);
  process.exit(1);
});
